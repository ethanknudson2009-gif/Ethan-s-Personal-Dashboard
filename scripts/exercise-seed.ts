/**
 * Writes a migration from the exercise library (src/lib/exercise-library.ts),
 * so the database and the app share one list. Safe to run again: existing
 * exercises are updated, missing ones added. Run with:
 *   node scripts/exercise-seed.ts 0020_more_exercises
 * (0019_exercise_library was the first one, then 0020, 0021.)
 */
import { writeFileSync } from "node:fs";

const file = process.argv[2] ?? "0019_exercise_library";
const num = file.slice(0, 4);
import { EXERCISE_LIBRARY, plain } from "../src/lib/exercise-library.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const rows = EXERCISE_LIBRARY.map((e) => `  (${q(e.name)}, ${q(e.muscle)}, ${q(e.equipment)}, ${e.bodyweight})`).join(",\n");
// Every name and nickname → the library name (to merge custom exercises made before).
const names = EXERCISE_LIBRARY.flatMap((e) => [e.name, ...e.aliases].map((a) => `  (${q(plain(a))}, ${q(e.name)})`));
const unique = [...new Set(names)].join(",\n");

const sql = `-- ${num}: the exercise library (${EXERCISE_LIBRARY.length} exercises). Generated by
-- scripts/exercise-seed.ts from src/lib/exercise-library.ts; edit those, not this file.

alter table public.exercises add column if not exists equipment text;

create temporary table lib (name text, muscle text, equipment text, bodyweight boolean);
insert into lib values
${rows};

-- Built-ins that already exist get their muscle group and equipment updated…
update public.exercises x
set muscle = lib.muscle, equipment = lib.equipment, bodyweight = lib.bodyweight
from lib
where x.user_id is null and lower(x.name) = lower(lib.name);

-- …and the rest are added.
insert into public.exercises (user_id, name, muscle, equipment, bodyweight)
select null, lib.name, lib.muscle, lib.equipment, lib.bodyweight
from lib
where not exists (select 1 from public.exercises x where x.user_id is null and lower(x.name) = lower(lib.name));

-- Exercises added by hand because the old list didn't have them ("Shoulder
-- Press", "Dumbbell row"…) are merged into the library one: their sets move
-- over, then the duplicate is removed.
create temporary table said (said text, name text);
insert into said values
${unique};

create temporary table merge as
select mine.id as old_id, builtin.id as new_id
from public.exercises mine
join said on said.said = trim(regexp_replace(regexp_replace(lower(mine.name), '[^a-z0-9 ]+', ' ', 'g'), ' +', ' ', 'g'))
join public.exercises builtin on builtin.user_id is null and builtin.name = said.name
where mine.user_id is not null;

update public.workout_sets s set exercise_id = m.new_id from merge m where s.exercise_id = m.old_id;
delete from public.exercises x using merge m where x.id = m.old_id;

drop table lib;
drop table said;
drop table merge;
`;
writeFileSync(new URL(`../supabase/migrations/${file}.sql`, import.meta.url), sql);
console.log(`Wrote ${EXERCISE_LIBRARY.length} exercises, ${new Set(names).size} names.`);
